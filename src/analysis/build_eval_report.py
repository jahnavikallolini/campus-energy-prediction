"""Assemble reports/model_evaluation_report.md from saved tables.

Usage:  python -m src.analysis.build_eval_report
The numeric sections are generated; the interpretation / problems text is read from
reports/model_evaluation_narrative.md (written after inspecting the results).
"""
import json

import pandas as pd

from src import config as C
from src.data.audit import md_table
from src.models import common as M

LAB = {b: v["label"] for b, v in C.BUILDINGS.items()}


def fmt(df):
    d = df.copy()
    for c in ("MAE", "RMSE"):
        if c in d: d[c] = d[c].map(lambda v: f"{v:,.0f}")
    if "MSE" in d: d["MSE"] = d["MSE"].map(lambda v: f"{v:.3e}")
    for c in ("R2", "nMAE_std", "nRMSE_std", "macro_R2", "macro_nMAE_std", "macro_nRMSE_std"):
        if c in d: d[c] = d[c].map(lambda v: f"{v:.3f}")
    for c in ("pooled_MAE_W", "pooled_RMSE_W"):
        if c in d: d[c] = d[c].map(lambda v: f"{v:,.0f}")
    if "n" in d: d["n"] = d["n"].map(lambda v: f"{int(v):,}")
    return d


def per_building(long, variant, subset, split):
    d = long[(long.variant == variant) & (long.subset == subset) & (long.eval_set == split)].copy()
    d["building"] = d.building.map(LAB)
    order = {b: i for i, b in enumerate(LAB.values())}
    d["o"] = d.building.map(order)
    d = d.sort_values(["o", "model"])
    return md_table(fmt(d[["building", "model", "n", "MAE", "MSE", "RMSE", "R2", "nMAE_std", "nRMSE_std"]]))


def main():
    long = pd.read_csv(C.TAB_DIR / "model_metrics_long.csv")
    mac = pd.read_csv(C.TAB_DIR / "model_metrics_macro.csv")
    sel = json.load(open(C.MET_DIR / "selected_config.json"))
    best = json.load(open(C.MET_DIR / "best_model.json"))
    split = json.load(open(C.MET_DIR / "split.json"))
    timing = pd.read_csv(C.TAB_DIR / "timings_and_clipping.csv")
    pv = pd.read_csv(C.TAB_DIR / "primary_vs_energy_only_macro.csv")
    pvb = pd.read_csv(C.TAB_DIR / "primary_vs_energy_only_best_model_by_building.csv")
    runtime = pd.read_csv(C.TAB_DIR / "runtime_summary_primary.csv")
    res = pd.read_csv(C.TAB_DIR / "residual_summary_best_model.csv")
    lz = pd.read_csv(C.TAB_DIR / "lecture_zero_analysis_test.csv")
    narr_path = C.REPORT_DIR / "model_evaluation_narrative.md"
    narrative = narr_path.read_text() if narr_path.exists() else "_(interpretation pending)_"

    cfg_rows = []
    for v, name in (("P", "P (energy + lagged occupancy)"), ("E_all", "Energy-only (E_all and E_matched)")):
        for m in M.MODELS:
            c = sel[v][m]
            cfg_rows.append(dict(feature_set=name, model=M.MODEL_NAMES[m], encoding=c["encoding"],
                                 hyperparameters=json.dumps(c["params"]), macro_val_nRMSE_std=f"{c['macro_val_nRMSE_std']:.4f}",
                                 macro_val_R2=f"{c['macro_val_R2']:.4f}", candidates_tried=c["n_candidates"]))
    def macro_tab(split_name, variant="P", subset="own"):
        d = mac[(mac.variant == variant) & (mac.subset == subset) & (mac.eval_set == split_name)].copy()
        d = d.sort_values("macro_nRMSE_std")
        return md_table(fmt(d[["model", "macro_R2", "macro_nMAE_std", "macro_nRMSE_std", "pooled_MAE_W", "pooled_RMSE_W"]]))
    pvt = pv.copy()
    pvt = pvt[pvt.setup.str.startswith(("P:", "E_matched", "E_all: energy-only, all train rows"))]
    pvt = pvt.sort_values(["eval_set", "model", "setup"])
    pvt["macro_R2"] = pvt.macro_R2.map(lambda v: f"{v:.3f}"); pvt["macro_nMAE_std"] = pvt.macro_nMAE_std.map(lambda v: f"{v:.3f}")
    pvt["macro_nRMSE_std"] = pvt.macro_nRMSE_std.map(lambda v: f"{v:.3f}"); pvt["rows"] = pvt.rows.map(lambda v: f"{int(v):,}")
    pvb2 = pvb.copy(); pvb2["building"] = pvb2.building.map(LAB)
    pvb2 = pvb2[pvb2.setup.str.startswith(("P:", "E_matched", "E_all: energy-only, all train rows"))].sort_values(["eval_set", "building", "setup"])
    for c in ("MAE", "RMSE"): pvb2[c] = pvb2[c].map(lambda v: f"{v:,.0f}")
    pvb2["R2"] = pvb2.R2.map(lambda v: f"{v:.3f}"); pvb2["nRMSE_std"] = pvb2.nRMSE_std.map(lambda v: f"{v:.3f}"); pvb2["n"] = pvb2.n.map(lambda v: f"{int(v):,}")
    tim = (timing.groupby(["variant", "model"]).agg(train_rows_total=("train_rows", "sum"), fit_seconds_total=("fit_seconds", "sum"),
                                                    predict_seconds_total=("predict_seconds", "sum"), predictions_clipped_at_0_val=("clipped_val", "sum"),
                                                    predictions_clipped_at_0_test=("clipped_test", "sum")).reset_index().round(2))
    rep = f"""# Model Evaluation Report (generated by src/analysis/build_eval_report.py)

Update (after the timestamp investigation, reports/timestamp_investigation.md): the primary test period is now 2017-01-01 to 2017-07-07; the full period of this report (to 2017-11-04) is a sensitivity analysis. Metrics by period: results/tables/period_metrics_*.csv and the IEEE report. Status of this document: regression experiments only. Anomaly detection, PCA, K-Means, the dashboard, the IEEE report and the presentation are not started.

## 1. Protocol
- Data: hourly mean `power` (W) of the seven main feeders; one model per building, identical procedure for every building.
- Split (fixed, global): train 2014-02-17 to 2016-06-30; validation 2016-07-01 to 2016-12-31; test 2017-01-01 to 2017-11-04.
- Missing occupancy stays missing; rows without occupancy lags are excluded from the primary matrix (P).
- Variants: **P** = energy + lagged occupancy (primary rows); **E_matched** = energy-only features, trained and scored on the same rows as P; **E_all** = energy-only features, trained on every eligible energy-only row inside the same date range (more rows because occupancy is not required), scored on all its rows and on the common rows shared with P.
- Encoding and hyperparameters were selected on validation only (one configuration per model and feature set, shared by all buildings) by the lowest macro-average validation nRMSE_std. The test set was not loaded by the tuning code.
- Frozen models are fitted on the training rows only and evaluated once on validation and test. Predictions are clipped at 0 W.
- Metrics: MAE, MSE, RMSE, R2 per building (primary metrics, in W / W^2). Because building scales differ by more than an order of magnitude, we also report nMAE_std = MAE / sigma_train and nRMSE_std = RMSE / sigma_train, where sigma_train is the building's training-target standard deviation (primary rows). nRMSE_std is about sqrt(1-R2) when the evaluation mean is close to the training mean. Macro averages weight all buildings equally; pooled values (rows-weighted, in W) are dominated by large buildings.

## 2. Model configurations (selected on validation)
{md_table(pd.DataFrame(cfg_rows))}

Decision Tree uses raw integer temporal columns (trees are invariant to monotone re-encodings). Linear Regression and Decision Tree are not scaled; KNN and SVR standardise numeric inputs and SVR also standardises the target (scalers fitted on training rows only). Cyclic encoding = sin/cos of hour (24), day of week (7), month (12). One-hot encoding of hour, day of week and month uses categories seen in training (Linear Regression drops the first level).

## 3. Validation results, primary variant P (per building and model)
{per_building(long, 'P', 'own', 'val')}

Macro summary (mean over buildings; pooled columns are rows-weighted and scale-dominated):

{macro_tab('val')}

## 4. Test results, primary variant P (frozen models, evaluated once)
{per_building(long, 'P', 'own', 'test')}

Macro summary:

{macro_tab('test')}

## 5. Reference baselines (not candidate models)
Persistence (power at t-1) and seasonal naive (power at t-24) on the same P rows.

Validation:

{per_building(long, 'baseline', 'own', 'val')}

Test:

{per_building(long, 'baseline', 'own', 'test')}

## 6. Primary (energy + lagged occupancy) vs energy-only
Macro averages on the **common rows** (rows that exist in the primary matrix), same models and procedure:

{md_table(pvt[['eval_set', 'model', 'setup', 'rows', 'macro_R2', 'macro_nMAE_std', 'macro_nRMSE_std']])}

Per building, selected model ({best['best_model']}):

{md_table(pvb2[['eval_set', 'building', 'setup', 'n', 'MAE', 'RMSE', 'R2', 'nRMSE_std']])}

## 7. Model selection (validation only)
Selected model: **{best['best_model']}** (criterion: {best['criterion']}). Validation ranking:

{md_table(pd.DataFrame(best['validation_ranking']).round(4))}

Per-building validation wins: {best['per_building_validation_wins']}.

## 8. Residuals, Lecture, runtime
Residual summary of the selected model (primary variant):

{md_table(res)}

Lecture (zero-inflated target), test period:

{md_table(lz)}

Training/prediction time and clipped predictions (all variants, sum over buildings, 1 CPU core):

{md_table(tim)}

## 9. Interpretation, problems and decisions needed
{narrative}

## Figures
fig11_validation_vs_test_nrmse, fig12_actual_vs_predicted, fig13_residual_distributions, fig14_error_by_hour, fig15_error_by_daytype_activity, fig16_primary_vs_energy_only, fig17_training_time, fig18_lecture_predictions (results/figures/).
"""
    (C.REPORT_DIR / "model_evaluation_report.md").write_text(rep)
    print("wrote reports/model_evaluation_report.md", len(rep), "chars")


if __name__ == "__main__":
    main()
