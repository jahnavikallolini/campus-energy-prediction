"""Assemble the preprocessing / coverage report from the saved tables.

Usage:  python -m src.data.coverage_report      (after build_features)
"""
import json

import numpy as np
import pandas as pd

from src import config as C
from src.data.audit import md_table
from src.features.build_features import ENERGY_ONLY_FEATURES, PRIMARY_FEATURES, TARGET

OCC_START, OCC_END = pd.Timestamp("2014-02-17"), pd.Timestamp("2017-11-04")


def main():
    feats = pd.read_csv(C.PROC_DIR / "hourly_features.csv.gz", parse_dates=["timestamp"])
    audit = pd.read_csv(C.TAB_DIR / "audit_energy_files.csv").set_index("building")
    split = json.load(open(C.MET_DIR / "split.json"))
    fill = json.load(open(C.MET_DIR / "fill_experiment.json"))
    grid_hours = feats[feats.building == "Academic"].shape[0]
    rows, loss = [], []
    for b, t in feats.groupby("building", sort=False):
        valid = t[t[TARGET].notna()]
        has_e = t[t.n_valid_min > 0]
        span = (has_e.timestamp.max() - has_e.timestamp.min()) // pd.Timedelta("1h") + 1
        prim, eo = t[t.eligible_primary], t[t.eligible_energy_only]
        rows.append(dict(building=b, minute_coverage_pct_of_full_grid=audit.loc[b, "share_of_full_grid_pct"],
                         first_energy=str(has_e.timestamp.min()), span_hours=int(span),
                         valid_hours=len(valid), valid_pct_of_span=round(100 * len(valid) / span, 1),
                         valid_pct_of_full_grid=round(100 * len(valid) / grid_hours, 1),
                         energy_only_rows=len(eo), primary_rows=len(prim),
                         primary_pct_of_valid=round(100 * len(prim) / len(valid), 1)))
        w = t[(t.timestamp >= OCC_START) & (t.timestamp <= OCC_END)]
        e_w = w[w.eligible_energy_only]
        lost = e_w[~e_w.eligible_primary]
        night = lambda x: round(100 * ((x.hour >= 20) | (x.hour < 8)).mean(), 1)
        loss.append(dict(building=b,
                         energy_only_before_occupancy_starts=int(((t.timestamp < OCC_START) & t.eligible_energy_only).sum()),
                         energy_only_after_occupancy_ends=int(((t.timestamp > OCC_END) & t.eligible_energy_only).sum()),
                         lost_inside_occupancy_window=len(lost),
                         lost_inside_pct=round(100 * len(lost) / max(len(e_w), 1), 1),
                         night_pct_of_energy_only_rows=night(e_w), night_pct_of_primary_rows=night(e_w[e_w.eligible_primary]),
                         night_pct_of_lost_rows=night(lost)))
    cov, lossdf = pd.DataFrame(rows), pd.DataFrame(loss)
    cov.to_csv(C.TAB_DIR / "coverage_summary.csv", index=False)
    lossdf.to_csv(C.TAB_DIR / "occupancy_loss_attribution.csv", index=False)
    el = feats[feats.eligible_primary]
    sc = el.pivot_table(index="building", columns="split", values=TARGET, aggfunc="size", fill_value=0)[["train", "val", "test"]]
    sc["total"] = sc.sum(axis=1)
    sc.reset_index().to_csv(C.TAB_DIR / "split_counts.csv", index=False)
    dates = el.groupby("split").timestamp.agg(first="min", last="max").loc[["train", "val", "test"]].astype(str)
    months = pd.crosstab(el.split, el.timestamp.dt.month).loc[["train", "val", "test"]]
    ed = pd.read_csv(C.TAB_DIR / "threshold_sensitivity_energy.csv").pivot(index="building", columns="min_valid_minutes", values="valid_hours")
    od = pd.read_csv(C.TAB_DIR / "threshold_sensitivity_occupancy.csv").pivot(index="building", columns="min_valid_obs", values="hours_with_energy_and_occupancy")
    gaps = pd.read_csv(C.TAB_DIR / "gap_runs_energy.csv").groupby("building").head(3)
    gd = pd.read_csv(C.TAB_DIR / "gap_run_distribution.csv").pivot(index="building", columns="gap_length", values="hours_missing")[["1 h", "2-3 h", "4-6 h", "7-24 h", "25 h-7 d", ">7 d"]]
    fe = pd.read_csv(C.TAB_DIR / "fill_experiment.csv")
    fe1 = fe[fe.gap_hours.isin([1, 2, 3])][["building", "gap_hours", "mae_locf_W", "mae_linear_W", "mae_lag24_W", "locf_beats_lag24"]].round(0)
    n_filled = round(100 * float((el.n_filled_inputs > 0).mean()), 2)
    rep = f"""# Preprocessing and coverage report (generated by src/data/coverage_report.py)

## Final hourly dataset
- Hourly grid: {grid_hours:,} hours per building (2013-08-10 00:00 to 2017-12-31 23:00 IST) x 7 buildings = {len(feats):,} rows, {feats.shape[1]} columns in `data/processed/hourly_features.csv.gz`.
- Target: `{TARGET}` = hourly mean of valid one-minute `power` readings, in {C.POWER_UNIT} (unit confirmed in the I-BLEND Data Descriptor). Valid hour: at least {C.MIN_VALID_ENERGY_MIN} of 60 readings.
- Primary model matrix: {int(feats.eligible_primary.sum()):,} rows x {len(PRIMARY_FEATURES)} features (rows with an observed target and all features available). Energy-only ablation rows: {int(feats.eligible_energy_only.sum()):,}.
- Primary features: {', '.join(PRIMARY_FEATURES)}.

## Coverage per building
{md_table(cov)}

## Threshold sensitivity (valid hours per building)
Energy, minimum valid minutes per hour:

{md_table(ed.reset_index())}

Hours with valid energy (>= {C.MIN_VALID_ENERGY_MIN} min) AND valid occupancy, minimum valid 10-min observations per hour:

{md_table(od.reset_index())}

## Missing periods
Hours missing by gap length (inside each building's logging span):

{md_table(gd.reset_index())}

Longest gaps:

{md_table(gaps)}

## Gap handling
Targets are never filled. For lag/rolling inputs only, a causal last-observation-carried-forward is allowed for at most {C.MAX_FILL_HOURS} h. Rule: the largest k <= 6 h for which carrying the last value beats the value from 24 h earlier in all seven buildings (masking experiment, 3,000 samples per building and k). Result: recommended {fill['recommended_max_fill_hours']} h; configured {fill['configured_MAX_FILL_HOURS']} h. Linear interpolation was more accurate in the experiment but uses the value after the gap, so it would leak the target and is not used for features.

{md_table(fe1)}

{n_filled}% of primary rows have at least one carried-forward input.

## Why rows are lost when occupancy lags are required
{md_table(lossdf)}

## Chronological split (global dates, chosen by a fixed rule from eligible-row counts)
- Rule: among month-boundary candidates with pooled shares in {C.SPLIT_TRAIN_SHARE_RANGE}/{C.SPLIT_VAL_SHARE_RANGE}/{C.SPLIT_TEST_SHARE_RANGE}, maximise the smallest per-building min(validation rows, test rows).
- Train: before {split['train_end']}; validation: {split['train_end']} to before {split['val_end']}; test: {split['val_end']} onward (until the last hour with occupancy lags, 2017-11-04 00:00).
- Pooled shares: {split['pooled_shares']}.

{md_table(dates.reset_index())}

Rows per building (primary matrix):

{md_table(sc.reset_index())}

Rows per calendar month by split (all buildings pooled):

{md_table(months.reset_index())}
"""
    (C.REPORT_DIR / "preprocessing_report.md").write_text(rep)
    print(cov.to_string()); print(lossdf.to_string())


if __name__ == "__main__":
    main()
